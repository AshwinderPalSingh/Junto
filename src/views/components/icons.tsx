import {
  AlarmClock,
  Ban,
  BookOpen,
  Camera,
  Check,
  Coffee,
  Compass,
  Dumbbell,
  Footprints,
  Hourglass,
  MapPinCheck,
  Megaphone,
  MessageSquare,
  Moon,
  Shield,
  ShieldCheck,
  Shirt,
  ShoppingBag,
  Sparkles,
  Sprout,
  Target,
  Timer,
  UserMinus,
  UserPlus,
  Users,
  Utensils,
  X,
  Zap,
  type LucideIcon,
} from "lucide-react";

/** Every icon referenced by name from config or view models (activities, badges, presets, notifications). */
const REGISTRY: Record<string, LucideIcon> = {
  coffee: Coffee,
  utensils: Utensils,
  footprints: Footprints,
  target: Target,
  dumbbell: Dumbbell,
  "shopping-bag": ShoppingBag,
  "book-open": BookOpen,
  "map-pin-check": MapPinCheck,
  timer: Timer,
  hourglass: Hourglass,
  shirt: Shirt,
  sparkles: Sparkles,
  sprout: Sprout,
  "shield-check": ShieldCheck,
  megaphone: Megaphone,
  compass: Compass,
  users: Users,
  "user-plus": UserPlus,
  "user-minus": UserMinus,
  check: Check,
  x: X,
  ban: Ban,
  "alarm-clock": AlarmClock,
  "message-square": MessageSquare,
  zap: Zap,
  moon: Moon,
  camera: Camera,
  shield: Shield,
};

export function Icon({ name, className, strokeWidth = 1.75 }: { name: string; className?: string; strokeWidth?: number }) {
  const Component = REGISTRY[name] ?? Sparkles;
  return <Component className={className} strokeWidth={strokeWidth} aria-hidden="true" />;
}
